def update_entry(text: str, uid: str, transform) -> tuple[str, bool]:
    pattern = re.compile(
        rf'(<content\s+contentuid="{re.escape(uid)}"\s+version="[^"]+">)(.*?)(</content>)',
        re.DOTALL,
    )
    matches = list(pattern.finditer(text))
    if len(matches) != 1:
        raise RuntimeError(f"Expected exactly one entry for {uid}, found {len(matches)}")
    old_inner = matches[0].group(2)
    new_inner = transform(old_inner)
    if new_inner == old_inner:
        return text, False
    return pattern.sub(lambda m: m.group(1) + new_inner + m.group(3), text, count=1), True


def main() -> None:
    text = TARGET.read_text(encoding="utf-8")
    changed = 0

    for uid, replacement in OVERRIDES.items():
        text, did_change = update_entry(text, uid, lambda _old, value=replacement: value)
        changed += did_change

    for uid, replacements in REPLACEMENTS.items():
        def transform(old: str, pairs=replacements, entry_uid=uid) -> str:
            updated = old
            for source, target in pairs:
                count = updated.count(source)
                if count == 0 and target not in updated:
                    raise RuntimeError(f"Expected {source!r} in {entry_uid}")
                updated = updated.replace(source, target)
            return updated

        text, did_change = update_entry(text, uid, transform)
        changed += did_change

    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"Updated {changed} localization entries in {TARGET}")


