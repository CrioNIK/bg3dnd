UID_OVERRIDES: dict[str, str] = {}


def assign(uids: str | tuple[str, ...], text: str) -> None:
    if isinstance(uids, str):
        uids = (uids,)
    for uid in uids:
        if uid in UID_OVERRIDES:
            raise ValueError(f"Duplicate translation override: {uid}")
        UID_OVERRIDES[uid] = text


