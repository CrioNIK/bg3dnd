def official_maps(target_text: str) -> tuple[dict[str, str], dict[str, str]]:
    en_nodes = ET.parse(BG_EN).getroot().findall("content")
    uk_nodes = ET.parse(BG_UK).getroot().findall("content")
    en_by_uid = {node.attrib["contentuid"]: node.text or "" for node in en_nodes}
    candidates: dict[str, collections.Counter[str]] = collections.defaultdict(collections.Counter)
    for node in uk_nodes:
        source = en_by_uid.get(node.attrib["contentuid"], "")
        target = node.text or ""
        if source and target:
            candidates[source][target] += 1

    target_lower = target_text.lower()
    result: dict[str, str] = {}
    exact: dict[str, str] = {}
    for source, targets in candidates.items():
        target = targets.most_common(1)[0][0]
        if (
            len(source) <= 120
            and "\n" not in source
            and "<" not in source
            and "[" not in source
            and "<" not in target
            and "[" not in target
            and CYRILLIC_RE.search(target)
        ):
            exact[source] = target
        words = re.findall(r"[A-Za-z][A-Za-z'’-]*", source)
        if (
            len(words) < 2
            or len(words) > 8
            or len(source) > 90
            or "\n" in source
            or "<" in source
            or "[" in source
            or not LATIN_RE.search(source)
            or source.lower() not in target_lower
        ):
            continue
        if len(targets) == 1 and CYRILLIC_RE.search(target) and "<" not in target and "[" not in target:
            result[source] = target
    return result, exact


def replace_phrase(text: str, source: str, target: str) -> str:
    left = r"(?<![A-Za-z])" if source[:1].isalnum() else ""
    right = r"(?![A-Za-z])" if source[-1:].isalnum() else ""
    return re.sub(left + re.escape(source) + right, target, text, flags=re.IGNORECASE)


def refine_visible(text: str, replacements: list[tuple[str, str]]) -> str:
    parts = TAG_SPLIT_RE.split(text)
    for index in range(0, len(parts), 2):
        visible = parts[index]
        for source, target in replacements:
            if source.lower() in visible.lower():
                visible = replace_phrase(visible, source, target)
        for pattern, target in POSTPROCESS:
            visible = re.sub(pattern, target, visible, flags=re.IGNORECASE)
        parts[index] = visible
    return "".join(parts)


def prefixed_title(source: str, exact: dict[str, str]) -> str | None:
    def translate_suffix(value: str) -> str | None:
        parts = value.split(": ")
        if len(parts) > 1:
            translated_parts = [
                EXACT_OVERRIDES.get(part) or MANUAL_PHRASES.get(part) or exact.get(part)
                for part in parts
            ]
            if all(translated_parts):
                return ": ".join(translated_parts)  # type: ignore[arg-type]
        return EXACT_OVERRIDES.get(value) or MANUAL_PHRASES.get(value) or exact.get(value)

    match = re.fullmatch(r"Level (\d+): (.+)", source)
    if match:
        suffix = match.group(2)
        translated = translate_suffix(suffix)
        if translated:
            return f"Рівень {match.group(1)}: {translated}"

    match = re.fullmatch(r"Feat: (.+)", source)
    if match:
        suffix = match.group(1)
        translated = translate_suffix(suffix)
        if translated:
            return f"Риса: {translated}"
    return None


def main() -> None:
    source_nodes = ET.parse(SOURCE).getroot().findall("content")
    source_by_uid = {node.attrib["contentuid"]: node.text or "" for node in source_nodes}
    tree = ET.parse(TARGET)
    all_target_text = "\n".join(node.text or "" for node in tree.getroot().findall("content"))
    official, official_exact = official_maps(all_target_text)

    combined = dict(official)
    combined.update(MANUAL_PHRASES)
    replacements = sorted(combined.items(), key=lambda item: len(item[0]), reverse=True)

    changed = 0
    overridden = 0
    for node in tree.getroot().findall("content"):
        source = source_by_uid[node.attrib["contentuid"]]
        before = node.text or ""
        if source in EXACT_OVERRIDES:
            after = EXACT_OVERRIDES[source]
            overridden += 1
        elif (title := prefixed_title(source, official_exact)) is not None:
            after = title
        else:
            after = refine_visible(before, replacements)
        if after != before:
            changed += 1
            node.text = after

    ET.indent(tree, space="  ")
    tree.write(TARGET, encoding="utf-8", xml_declaration=True, short_empty_elements=False)
    print(
        f"changed={changed} exact_overrides={overridden} "
        f"official_phrases={len(official)} total_phrases={len(replacements)}"
    )


if __name__ == "__main__":
    main()
